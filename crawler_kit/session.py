import json
import os
from pathlib import Path


# ── Netscape cookie 格式（yt-dlp / curl 兼容）──

def parse_netscape_cookies(path) -> list:
    """解析 Netscape cookie 文件，返回 [{name, value, domain, path, expires, secure, http_only}]。"""
    cookies = []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
    except OSError:
        return cookies
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 7:
            continue
        domain, flag, path_, secure, expires, name, value = parts[:7]
        cookies.append({
            "name": name,
            "value": value,
            "domain": domain,
            "path": path_,
            "expires": expires,
            "secure": secure == "TRUE",
            "http_only": flag == "TRUE",
        })
    return cookies


def cookies_to_netscape(cookies: list) -> str:
    """把 cookie 字典列表序列化为 Netscape 格式文本。"""
    lines = ["# Netscape HTTP Cookie File", "# generated by crawler_kit.session", ""]
    for c in cookies:
        lines.append("\t".join([
            c.get("domain", ""),
            "TRUE" if c.get("http_only") else "FALSE",
            c.get("path", "/"),
            "TRUE" if c.get("secure") else "FALSE",
            str(c.get("expires", "0")),
            c.get("name", ""),
            c.get("value", ""),
        ]))
    return "\n".join(lines) + "\n"


def cookie_str(cookies: list) -> str:
    """Cookie 列表 → 请求头 Cookie 字符串。"""
    return "; ".join(f"{c['name']}={c['value']}" for c in cookies)


# ── Cookie 字典 JSON 持久化（免登录复用）──

def save_cookies_to_file(cookie_dict: dict, filepath) -> bool:
    try:
        p = Path(filepath)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(cookie_dict, ensure_ascii=False, indent=2), encoding="utf-8")
        return True
    except Exception:
        return False


def load_cookies_from_file(filepath) -> dict:
    try:
        data = json.loads(Path(filepath).read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


# ── Playwright 登录态导出（可选依赖）──

def export_cookies_with_playwright(output_path, user_data_dir=None, url="https://www.bilibili.com") -> bool:
    """用 Playwright 启动本机 Chrome（持久化用户数据），访问 url 后导出 Cookie 为 Netscape 格式。

    user_data_dir 缺省 = 当前用户 Chrome User Data（自动带上登录状态）。
    敏感信息红线：导出文件含登录态，本地保留、不进仓（.gitignore）。
    """
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return False
    udd = user_data_dir or str(Path.home() / "AppData" / "Local" / "Google" / "Chrome" / "User Data")
    try:
        with sync_playwright() as p:
            context = p.chromium.launch_persistent_context(
                user_data_dir=udd, headless=True, channel="chrome")
            page = context.pages[0] if context.pages else context.new_page()
            page.goto(url, wait_until="networkidle", timeout=30000)
            cookies = page.context.cookies()
            context.close()
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        Path(output_path).write_text(cookies_to_netscape(cookies), encoding="utf-8")
        return True
    except Exception:
        return False
